#!/bin/bash
# Switch Catalyst to Gateway Mode (Groq/Fireworks/GLM via LiteLLM)
# Controlled by {{ORCHESTRATOR_NAME}} via natural language or /use-gateway command

set -e

GATEWAY_STATE_FILE="$HOME/.claude/gateway-mode"
SHELL_RC="$HOME/.bashrc"

echo "🔄 Switching to Gateway Mode..."
echo

# Check if LiteLLM proxy is running
if ! curl -s http://localhost:4000/health > /dev/null 2>&1; then
    echo "⚠️  LiteLLM proxy not running on localhost:4000"
    echo "   Starting it now..."
    cd {{CATALYST_ROOT}}/tools/litellm
    ./start_proxy.sh
    sleep 2
fi

# Write state file
echo "gateway" > "$GATEWAY_STATE_FILE"
echo "✅ Gateway mode state saved to $GATEWAY_STATE_FILE"

# Check if shell profile has gateway logic
if ! grep -q "CLAUDE_GATEWAY_MODE" "$SHELL_RC" 2>/dev/null; then
    echo >> "$SHELL_RC"
    echo "# Catalyst Gateway Toggle - Auto-generated by use-gateway.sh" >> "$SHELL_RC"
    echo 'if [ -f "$HOME/.claude/gateway-mode" ]; then' >> "$SHELL_RC"
    echo '    GATEWAY_MODE=$(cat "$HOME/.claude/gateway-mode" 2>/dev/null || echo "subscription")' >> "$SHELL_RC"
    echo '    if [ "$GATEWAY_MODE" = "gateway" ]; then' >> "$SHELL_RC"
    echo '        export ANTHROPIC_BASE_URL=http://localhost:4000' >> "$SHELL_RC"
    echo '        export ANTHROPIC_AUTH_TOKEN=sk-litellm-builderOS-2025' >> "$SHELL_RC"
    echo '        export CLAUDE_GATEWAY_MODE=enabled' >> "$SHELL_RC"
    echo '    fi' >> "$SHELL_RC"
    echo 'fi' >> "$SHELL_RC"
    echo "✅ Added gateway toggle logic to $SHELL_RC"
else
    echo "✅ Shell profile already configured for gateway toggle"
fi

echo
echo "🎯 Gateway Mode Configuration Complete"
echo
echo "   Current session: Subscription (no change until restart)"
echo "   Next session: Gateway → Groq/Fireworks/GLM via LiteLLM"
echo
echo "📋 Available models in gateway mode:"
echo "   • groq-builder (Llama 3.3 70B) - \$0.59-0.79/M tokens"
echo "   • groq-fast (Llama 3.1 8B) - \$0.05-0.08/M tokens"
echo "   • glm-builder (GLM-4.6 352B MoE) - \$0.55-2.19/M tokens"
echo "   • fireworks-standard (Llama 70B) - \$0.90/M tokens"
echo
echo "🔄 To activate: Start new terminal → run 'claude' command"
echo "💡 To switch back: Tell {{ORCHESTRATOR_NAME}} 'use subscription' or run /use-subscription"
echo
