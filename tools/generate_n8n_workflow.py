#!/usr/bin/env python3
"""
Catalyst - n8n Workflow Generation
Generates n8n workflows from capsule specifications using n8n-mcp integration
"""

import os
import sys
import yaml
import json
import subprocess
from pathlib import Path
from datetime import datetime
from typing import Dict, List, Any, Optional

# Catalyst paths
BUILDER_ROOT = Path.home() / "Documents" / "Builder"

class N8nWorkflowGenerator:
    def __init__(self, capsule_path: Path, agent_mode: bool = False):
        self.capsule_path = Path(capsule_path)
        self.agent_mode = agent_mode
        self.spec_path = self.capsule_path / "spec" / "requirements.yaml"
        self.workflows_src = self.capsule_path / "src" / "automation" / "n8n"
        self.workflows_ops = self.capsule_path / "ops" / "n8n"
        
        # Create directories
        self.workflows_src.mkdir(parents=True, exist_ok=True)
        self.workflows_ops.mkdir(parents=True, exist_ok=True)
        
    def load_spec(self) -> Dict[str, Any]:
        """Load capsule specification"""
        if not self.spec_path.exists():
            raise FileNotFoundError(f"Specification not found: {self.spec_path}")
            
        with open(self.spec_path, 'r') as f:
            return yaml.safe_load(f)
    
    def generate_workflow_json(self, workflow_spec: Dict[str, Any]) -> Dict[str, Any]:
        """Generate n8n workflow JSON from specification"""
        name = workflow_spec.get('name', 'Unnamed Workflow')
        description = workflow_spec.get('description', 'Generated by Catalyst')
        triggers = workflow_spec.get('triggers', [])
        actions = workflow_spec.get('actions', [])
        
        # Base workflow structure
        workflow = {
            "name": name,
            "nodes": [],
            "connections": {},
            "active": False,
            "settings": {
                "saveExecutionProgress": True,
                "saveManualExecutions": True
            },
            "createdAt": datetime.now().isoformat(),
            "updatedAt": datetime.now().isoformat(),
            "tags": ["builder-system", self.capsule_path.name]
        }
        
        node_positions = self._calculate_node_positions(triggers, actions)
        
        # Generate trigger nodes
        trigger_nodes = []
        for i, trigger in enumerate(triggers):
            node = self._create_trigger_node(trigger, node_positions[f"trigger_{i}"])
            trigger_nodes.append(node)
            workflow["nodes"].append(node)
        
        # Generate action nodes
        action_nodes = []
        for i, action in enumerate(actions):
            node = self._create_action_node(action, node_positions[f"action_{i}"])
            action_nodes.append(node)
            workflow["nodes"].append(node)
        
        # Add Catalyst logging node
        log_node = self._create_builder_log_node(node_positions["log"])
        workflow["nodes"].append(log_node)
        
        # Generate connections
        workflow["connections"] = self._generate_connections(trigger_nodes, action_nodes, log_node)
        
        return workflow
    
    def _calculate_node_positions(self, triggers: List, actions: List) -> Dict[str, List[int]]:
        """Calculate node positions for workflow layout"""
        positions = {}
        
        # Starting positions
        x_start = 100
        y_start = 200
        x_spacing = 300
        y_spacing = 100
        
        # Position triggers
        for i in range(len(triggers)):
            positions[f"trigger_{i}"] = [x_start, y_start + (i * y_spacing)]
        
        # Position actions  
        action_x = x_start + x_spacing
        for i in range(len(actions)):
            positions[f"action_{i}"] = [action_x, y_start + (i * y_spacing)]
        
        # Position logging node
        positions["log"] = [action_x + x_spacing, y_start]
        
        return positions
    
    def _create_trigger_node(self, trigger_spec: Dict[str, Any], position: List[int]) -> Dict[str, Any]:
        """Create trigger node from specification"""
        trigger_type = trigger_spec.get('type', 'manual')
        name = trigger_spec.get('name', f'{trigger_type.title()} Trigger')
        
        if trigger_type == 'webhook':
            return {
                "name": name,
                "type": "n8n-nodes-base.webhook",
                "position": position,
                "webhookId": trigger_spec.get('webhook_id', ''),
                "parameters": {
                    "path": trigger_spec.get('path', f"builder/{self.capsule_path.name}"),
                    "httpMethod": trigger_spec.get('method', 'POST').upper(),
                    "responseMode": "responseNode",
                    "options": {
                        "rawBody": trigger_spec.get('raw_body', False)
                    }
                }
            }
        
        elif trigger_type == 'schedule':
            return {
                "name": name,
                "type": "n8n-nodes-base.scheduleTrigger", 
                "position": position,
                "parameters": {
                    "rule": {
                        "interval": [
                            {
                                "field": "cronExpression",
                                "value": trigger_spec.get('cron', '0 9 * * *')
                            }
                        ]
                    }
                }
            }
        
        elif trigger_type == 'manual':
            return {
                "name": name,
                "type": "n8n-nodes-base.manualTrigger",
                "position": position,
                "parameters": {}
            }
        
        else:
            # Default to manual trigger
            return {
                "name": f"Unknown Trigger ({trigger_type})",
                "type": "n8n-nodes-base.manualTrigger",
                "position": position,
                "parameters": {}
            }
    
    def _create_action_node(self, action_spec: Dict[str, Any], position: List[int]) -> Dict[str, Any]:
        """Create action node from specification"""
        action_type = action_spec.get('type', 'http_request')
        name = action_spec.get('name', f'{action_type.title()} Action')
        parameters = action_spec.get('parameters', {})
        
        if action_type == 'http_request':
            return {
                "name": name,
                "type": "n8n-nodes-base.httpRequest",
                "position": position,
                "parameters": {
                    "url": parameters.get('url', 'https://api.example.com'),
                    "method": parameters.get('method', 'GET').upper(),
                    "sendHeaders": bool(parameters.get('headers')),
                    "headerParameters": self._format_headers(parameters.get('headers', {})),
                    "sendBody": bool(parameters.get('body')),
                    "bodyParameters": self._format_body_params(parameters.get('body', {})),
                    "options": {
                        "timeout": parameters.get('timeout', 30000)
                    }
                }
            }
        
        elif action_type == 'function':
            return {
                "name": name,
                "type": "n8n-nodes-base.function",
                "position": position,
                "parameters": {
                    "functionCode": parameters.get('code', '// Catalyst function\nreturn [{json: $json}];')
                }
            }
        
        elif action_type == 'code':
            return {
                "name": name,
                "type": "n8n-nodes-base.code",
                "position": position,
                "parameters": {
                    "language": parameters.get('language', 'javascript'),
                    "jsCode": parameters.get('code', '// Catalyst code\nfor (const item of $input.all()) {\n  $return.push({json: item.json});\n}')
                }
            }
        
        elif action_type == 'condition':
            return {
                "name": name,
                "type": "n8n-nodes-base.if",
                "position": position,
                "parameters": {
                    "conditions": {
                        "options": {
                            "caseSensitive": True,
                            "leftValue": "",
                            "typeValidation": "strict"
                        },
                        "conditions": [
                            {
                                "id": "condition1",
                                "leftValue": parameters.get('left_value', '={{$json.status}}'),
                                "rightValue": parameters.get('right_value', 'success'),
                                "operator": {
                                    "type": "string",
                                    "operation": parameters.get('operator', 'equals')
                                }
                            }
                        ],
                        "combinator": "and"
                    }
                }
            }
        
        elif action_type == 'set_data':
            return {
                "name": name,
                "type": "n8n-nodes-base.set",
                "position": position,
                "parameters": {
                    "mode": "manual",
                    "values": self._format_set_values(parameters.get('values', {}))
                }
            }
        
        else:
            # Default to function node with error
            return {
                "name": f"Unknown Action ({action_type})",
                "type": "n8n-nodes-base.function",
                "position": position,
                "parameters": {
                    "functionCode": f"// Unknown action type: {action_type}\nthrow new Error('Unknown action type: {action_type}');"
                }
            }
    
    def _create_builder_log_node(self, position: List[int]) -> Dict[str, Any]:
        """Create Catalyst event logging node"""
        return {
            "name": "Log Builder Event",
            "type": "n8n-nodes-base.function",
            "position": position,
            "parameters": {
                "functionCode": f"""// Catalyst event logging
const event = {{
  type: 'n8n_workflow_execution',
  capsule: '{self.capsule_path.name}',
  workflow: $workflow.name,
  status: $json.status || 'completed',
  timestamp: new Date().toISOString(),
  data: $json
}};

// Format for Builder event log
const logEntry = `${{event.type}}|${{event.capsule}}|${{event.status}}|${{event.timestamp}}`;

return [{{
  json: {{
    ...event,
    logEntry: logEntry,
    builderSystem: true
  }}
}}];"""
            }
        }
    
    def _format_headers(self, headers: Dict[str, str]) -> Dict[str, List]:
        """Format headers for n8n HTTP node"""
        if not headers:
            return {"parameters": []}
        
        return {
            "parameters": [
                {"name": key, "value": value}
                for key, value in headers.items()
            ]
        }
    
    def _format_body_params(self, body: Dict[str, Any]) -> Dict[str, List]:
        """Format body parameters for n8n HTTP node"""
        if not body:
            return {"parameters": []}
        
        return {
            "parameters": [
                {"name": key, "value": str(value)}
                for key, value in body.items()
            ]
        }
    
    def _format_set_values(self, values: Dict[str, Any]) -> Dict[str, List]:
        """Format values for n8n Set node"""
        formatted = {
            "string": [],
            "number": [],
            "boolean": []
        }
        
        for key, value in values.items():
            if isinstance(value, str):
                formatted["string"].append({"name": key, "value": value})
            elif isinstance(value, (int, float)):
                formatted["number"].append({"name": key, "value": value})
            elif isinstance(value, bool):
                formatted["boolean"].append({"name": key, "value": value})
            else:
                # Default to string
                formatted["string"].append({"name": key, "value": str(value)})
        
        return formatted
    
    def _generate_connections(self, trigger_nodes: List, action_nodes: List, log_node: Dict) -> Dict[str, Any]:
        """Generate node connections"""
        connections = {}
        
        # Connect triggers to first action
        if trigger_nodes and action_nodes:
            for trigger in trigger_nodes:
                connections[trigger["name"]] = {
                    "main": [[{"node": action_nodes[0]["name"], "type": "main", "index": 0}]]
                }
        
        # Connect actions in sequence
        for i, action in enumerate(action_nodes[:-1]):
            next_action = action_nodes[i + 1]
            connections[action["name"]] = {
                "main": [[{"node": next_action["name"], "type": "main", "index": 0}]]
            }
        
        # Connect last action to logging
        if action_nodes:
            connections[action_nodes[-1]["name"]] = {
                "main": [[{"node": log_node["name"], "type": "main", "index": 0}]]
            }
        elif trigger_nodes:
            # If no actions, connect trigger directly to logging
            for trigger in trigger_nodes:
                connections[trigger["name"]] = {
                    "main": [[{"node": log_node["name"], "type": "main", "index": 0}]]
                }
        
        return connections
    
    def save_workflow(self, workflow: Dict[str, Any]) -> Path:
        """Save workflow JSON to file"""
        workflow_name = workflow["name"].replace(" ", "_").lower()
        workflow_file = self.workflows_src / f"{workflow_name}.json"
        
        with open(workflow_file, 'w') as f:
            json.dump(workflow, f, indent=2)
        
        return workflow_file
    
    def deploy_to_n8n(self, workflow_file: Path) -> bool:
        """Deploy workflow to n8n instance via MCP (if available)"""
        try:
            if not self.agent_mode:
                print(f"📤 Deploying workflow to n8n: {workflow_file.name}")
            
            # Note: This would use n8n-mcp tools in actual implementation
            # For now, just copy to ops directory as "deployed"
            deployed_file = self.workflows_ops / workflow_file.name
            with open(workflow_file, 'r') as src, open(deployed_file, 'w') as dst:
                dst.write(src.read())
            
            if not self.agent_mode:
                print(f"✅ Workflow deployed: {deployed_file}")
                print("💡 Use n8n-mcp tools for actual n8n instance deployment")
            
            return True
            
        except Exception as e:
            print(f"❌ Deployment failed: {e}")
            return False
    
    def generate_all_workflows(self):
        """Generate all workflows defined in capsule spec"""
        try:
            spec = self.load_spec()
            workflows = spec.get('workflows', [])
            
            if not workflows:
                if not self.agent_mode:
                    print(f"ℹ️  No workflows defined in {self.spec_path}")
                return
            
            # Generate workflows
            generated_count = 0
            deployed_count = 0
            
            for workflow_spec in workflows:
                if not self.agent_mode:
                    print(f"\n📝 Generating workflow: {workflow_spec.get('name', 'Unnamed')}")
                
                # Generate workflow JSON
                workflow = self.generate_workflow_json(workflow_spec)
                
                # Save to file
                workflow_file = self.save_workflow(workflow)
                generated_count += 1
                
                if self.agent_mode:
                    print(f"Generated workflow: {workflow['name']}")
                else:
                    print(f"📄 Generated: {workflow_file}")
                
                # Deploy to n8n
                if self.deploy_to_n8n(workflow_file):
                    deployed_count += 1
            
            if self.agent_mode:
                print(f"✅ Generated {deployed_count}/{generated_count} workflows")
            else:
                print(f"\n🎉 Generated {generated_count} workflows, deployed {deployed_count} successfully")
                print(f"📁 Workflows available in: {self.workflows_ops}")
            
        except Exception as e:
            print(f"❌ Error generating workflows: {e}")
            sys.exit(1)

def main():
    """Main entry point"""
    if len(sys.argv) < 2 or len(sys.argv) > 3:
        print("Usage: generate_n8n_workflow.py <capsule_path> [--agent]")
        print("Example: generate_n8n_workflow.py {{CATALYST_ROOT}}/capsules/my-capsule")
        print("Example: generate_n8n_workflow.py {{CATALYST_ROOT}}/capsules/my-capsule --agent")
        print()
        print("Modes:")
        print("  --agent  - Agent automation mode (minimal output)")
        sys.exit(1)
    
    capsule_path = Path(sys.argv[1]).expanduser()
    agent_mode = "--agent" in sys.argv
    
    if not capsule_path.exists():
        print(f"❌ Capsule path does not exist: {capsule_path}")
        sys.exit(1)
    
    if agent_mode:
        print("🤖 Agent Mode: Automated n8n workflow generation")
    else:
        print(f"🚀 Catalyst - n8n Workflow Generation")
        print(f"📁 Capsule: {capsule_path.name}")
        print(f"📍 Path: {capsule_path}")
        print()
    
    generator = N8nWorkflowGenerator(capsule_path, agent_mode)
    generator.generate_all_workflows()

if __name__ == "__main__":
    main()